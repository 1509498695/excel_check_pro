    // 保留原有业务逻辑：SVN 更新继续复用原有工作副本更新接口。
    await store.runSvnUpdate()
    await ensureStepExpanded(4)
    await scrollToStep(4)
    ElMessage.success(store.svnUpdateSummary || 'SVN 更新完成。')
  } catch {
    // 页面级错误由 store 托管。
    await ensureStepExpanded(4)
    await scrollToStep(4)
  }
}
